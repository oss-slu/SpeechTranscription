"""Generate Saltify 2.0 CSS custom properties from design-tokens.json.

Usage:
    python scripts/build_design_tokens.py          # write design-tokens.css
    python scripts/build_design_tokens.py --check  # exit 1 if the CSS is stale
    python scripts/build_design_tokens.py --report # print contrast ratios

The JSON file is the single source of truth (see issue #361). The generated CSS
is framework-neutral, so it can be consumed by whichever desktop runtime #348
selects (Electron, Tauri, or a Python webview host all render HTML/CSS).
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKEN_DIR = ROOT / "docs" / "saltify-2.0" / "design-system"
TOKENS_JSON = TOKEN_DIR / "design-tokens.json"
TOKENS_CSS = TOKEN_DIR / "design-tokens.css"

HEX_RE = re.compile(r"^#[0-9A-Fa-f]{6}$")


def load_tokens(path=TOKENS_JSON):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def _block(selector, values, indent="  "):
    lines = [f"{selector} {{"]
    lines.extend(f"{indent}--{key}: {value};" for key, value in values.items())
    lines.append("}")
    return "\n".join(lines)


def render_css(tokens):
    """Render the token model as CSS.

    Theme resolution order:
      1. [data-theme="light"|"dark"] on <html> (explicit user choice) wins.
      2. Otherwise prefers-color-scheme follows the OS setting.
    Light is the fallback when neither applies.
    """
    light = tokens["themes"]["light"]
    dark = tokens["themes"]["dark"]
    parts = [
        "/* Generated by scripts/build_design_tokens.py from design-tokens.json. */",
        "/* Do not edit by hand. */",
        "",
        _block(":root", tokens["base"]),
        "",
        _block(':root,\n:root[data-theme="light"]', light),
        "",
        "@media (prefers-color-scheme: dark) {",
        _block('  :root:not([data-theme="light"])', dark, "    "),
        "}",
        "",
        _block(':root[data-theme="dark"]', dark),
        "",
        ':root, :root[data-theme="light"] { color-scheme: light; }',
        ':root[data-theme="dark"] { color-scheme: dark; }',
        '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { color-scheme: dark; } }',
        "",
        "/* Reduced motion: honour the OS setting and the in-app override. */",
        "@media (prefers-reduced-motion: reduce) {",
        "  :root {",
        "    --motion-duration-fast: 0ms;",
        "    --motion-duration-base: 0ms;",
        "    --motion-duration-slow: 0ms;",
        "  }",
        "}",
        ':root[data-motion="reduce"] {',
        "  --motion-duration-fast: 0ms;",
        "  --motion-duration-base: 0ms;",
        "  --motion-duration-slow: 0ms;",
        "}",
        "",
    ]
    return "\n".join(parts)


def _channel(value):
    value /= 255
    return value / 12.92 if value <= 0.03928 else ((value + 0.055) / 1.055) ** 2.4


def relative_luminance(hex_color):
    if not HEX_RE.match(hex_color):
        raise ValueError(f"Contrast checks need a 6-digit hex colour, got {hex_color!r}")
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * _channel(r) + 0.7152 * _channel(g) + 0.0722 * _channel(b)


def contrast_ratio(fg, bg):
    """WCAG 2.x contrast ratio between two opaque hex colours."""
    lighter, darker = sorted((relative_luminance(fg), relative_luminance(bg)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


def contrast_results(tokens):
    """Yield (theme, kind, fg, bg, ratio, minimum) for every declared pair."""
    for theme_name, theme in tokens["themes"].items():
        for kind, spec in tokens["contrastPairs"].items():
            for fg, bg in spec["pairs"]:
                ratio = contrast_ratio(theme[fg], theme[bg])
                yield theme_name, kind, fg, bg, ratio, spec["minimum"]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if design-tokens.css is out of date")
    parser.add_argument("--report", action="store_true", help="print every contrast ratio")
    args = parser.parse_args(argv)

    tokens = load_tokens()
    css = render_css(tokens)

    if args.report:
        for theme, kind, fg, bg, ratio, minimum in contrast_results(tokens):
            flag = "ok  " if ratio >= minimum else "FAIL"
            print(f"{flag} {theme:5} {kind:7} {ratio:5.2f} (min {minimum}) {fg} on {bg}")
        return 0

    if args.check:
        current = TOKENS_CSS.read_text(encoding="utf-8") if TOKENS_CSS.exists() else ""
        if current != css:
            print("design-tokens.css is stale; run python scripts/build_design_tokens.py", file=sys.stderr)
            return 1
        print("design-tokens.css is up to date")
        return 0

    TOKENS_CSS.write_text(css, encoding="utf-8", newline="\n")
    print(f"Wrote {TOKENS_CSS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
